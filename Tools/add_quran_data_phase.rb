#!/usr/bin/env ruby
# frozen_string_literal: true

# Wires the Quran's full (QUL) data into the app target: the page-font folder, and the build phase
# that refuses a Release build without the full data.
#
# Run from the repository root, once:
#
#     ruby Tools/add_quran_data_phase.rb
#
# It is a script rather than a set of instructions because CLAUDE.md forbids hand-editing
# `project.pbxproj`, and the `xcodeproj` gem writes the same structures Xcode does. It is
# idempotent: run again and it reports that there is nothing to do.
#
# What it sets up, and why (QURAN_MIGRATION_PLAN.md, T1, T4, T14):
#
#   * `QuranData/Fonts/madaniV2` as a **folder reference** in the app's Copy Bundle Resources —
#     not a synchronized group, which would flatten the 604 `p<N>.ttf` files into the bundle root.
#     A folder reference keeps the `madaniV2/` path the page renderer reads and `FontRegistrar`
#     skips. The folder is committed holding only a README, so a public clone still has something
#     to copy and builds; `Tools/QuranBuilder --profile qul` fills it locally.
#
#   * a "Check Quran full data" run-script phase. A **Release** build fails, with the command that
#     fixes it, if the full database, any QUL pack or any of the 604 page fonts is missing: an App
#     Store build must never ship the fallback by accident. A **Debug** build only warns, so a
#     public clone builds and runs on the Tanzil fallback.
#
#     The script reads `$(SRCROOT)/QuranData`, the one input it declares: user-script sandboxing
#     lets a phase read only its declared inputs, and declaring the individual files would make a
#     missing one a build error in Debug too. Inside a declared folder the sandbox lets the script
#     test files by name, so every expected file is named rather than listed from the folder.
#
#     Until M3 moves the full database and packs into the app's resources, the phase checks them
#     where `Tools/QuranBuilder` writes them, `QuranData/out/qul/`. M3 repoints it.
#
# Both pieces belong to the app target only: the widget and the notification extension never draw
# a Mushaf page.

require 'xcodeproj'

PROJECT     = 'ThawabForGod.xcodeproj'
APP         = 'ThawabForGod'
GROUP       = 'QuranData'
FOLDER      = 'Fonts/madaniV2'
PHASE_NAME  = 'Check Quran full data'

SCRIPT = <<~'SH'
  # Generated by Tools/add_quran_data_phase.rb — edit there and re-run, not here.
  # Release fails without the full Quran data; Debug warns (QURAN_MIGRATION_PLAN.md, T4).
  data="$SRCROOT/QuranData"
  build="swift run -c release --package-path Tools/QuranBuilder QuranBuilder --profile qul"
  missing=""

  for file in out/qul/quran-mushaf.sqlite \
              out/qul/Packs/translation-en-sahih-international.sqlite \
              out/qul/Packs/tafsir-ar-muyassar.sqlite \
              out/qul/Packs/tafsir-en-mukhtasar.sqlite \
              out/qul/Packs/surah-info-en.sqlite; do
    [ -s "$data/$file" ] || missing="$missing QuranData/$file"
  done

  # The sandbox may test files but not list folders, so every page font is named.
  fonts=0
  i=1
  while [ $i -le 604 ]; do
    [ -s "$data/Fonts/madaniV2/p$i.ttf" ] && fonts=$((fonts + 1))
    i=$((i + 1))
  done
  [ $fonts -eq 604 ] || missing="$missing QuranData/Fonts/madaniV2 ($fonts of 604 page fonts)"

  if [ -n "$missing" ]; then
    message="the full Quran data is missing:$missing. Build it from QuranData/raw with: $build (see QuranData/SOURCES.md). Without it the app runs on the Tanzil fallback."
    if [ "$CONFIGURATION" = "Release" ]; then
      echo "error: $message A Release build must ship the full data."
      exit 1
    fi
    echo "warning: $message"
  fi

  touch "$DERIVED_FILE_DIR/quran-full-data-checked"
SH

project = Xcodeproj::Project.open(PROJECT)
app = project.targets.find { |t| t.name == APP } or abort "No target named #{APP}."
changed = false

# The folder reference, in a QuranData group at the project root.
group = project.main_group.children.find { |c| c.isa == 'PBXGroup' && c.path == GROUP }
unless group
  group = project.main_group.new_group(GROUP, GROUP)
  changed = true
end

folder = group.children.find { |c| c.isa == 'PBXFileReference' && c.path == FOLDER }
unless folder
  folder = group.new_reference(FOLDER)
  folder.last_known_file_type = 'folder'
  folder.name = File.basename(FOLDER)
  changed = true
end

unless app.resources_build_phase.files_references.include?(folder)
  app.resources_build_phase.add_file_reference(folder)
  changed = true
end

# The guard, before the resources are copied.
phase = app.shell_script_build_phases.find { |p| p.name == PHASE_NAME }
unless phase
  phase = app.new_shell_script_build_phase(PHASE_NAME)
  app.build_phases.move(phase, app.build_phases.index(app.resources_build_phase))
  changed = true
end

wanted = {
  shell_script: SCRIPT,
  shell_path: '/bin/sh',
  input_paths: ['$(SRCROOT)/QuranData'],
  output_paths: ['$(DERIVED_FILE_DIR)/quran-full-data-checked'],
  always_out_of_date: '1',
  show_env_vars_in_log: '0',
}
wanted.each do |attribute, value|
  next if phase.send(attribute) == value

  phase.send("#{attribute}=", value)
  changed = true
end

unless changed
  puts "#{FOLDER} and '#{PHASE_NAME}' are already in #{APP} — nothing to do."
  exit 0
end

project.save

puts "Referenced #{GROUP}/#{FOLDER} as a folder and added '#{PHASE_NAME}' to #{APP}."
puts 'Next: xcodebuild build -scheme ThawabForGod -project ThawabForGod.xcodeproj ' \
     "-destination 'platform=iOS Simulator,name=iPhone 17' -quiet"
